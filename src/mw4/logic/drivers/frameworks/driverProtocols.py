"""Back-end protocols per device family: the calls a device facade makes on the
entries of its run table (see DeviceFacade.run)."""

from mw4.base.driverProtocol import FrameworkDriver, HasDriverConfig
from pathlib import Path
from typing import Any, ClassVar, Protocol, runtime_checkable


@runtime_checkable
class CameraDriver(FrameworkDriver, Protocol):
    def sendDownloadMode(self) -> None: ...

    def expose(self) -> None: ...

    def abort(self) -> bool | None: ...

    def sendCoolerSwitch(self, coolerOn: bool = False) -> None: ...

    def sendCoolerTemp(self, temperature: float = 0) -> None: ...

    def sendOffset(self, offset: int = 0) -> None: ...

    def sendGain(self, gain: int = 0) -> None: ...


@runtime_checkable
class DomeDriver(FrameworkDriver, Protocol):
    def slewToAltAz(self, altitude: float, azimuth: float) -> None: ...

    def openShutter(self) -> None: ...

    def closeShutter(self) -> None: ...

    def slewCW(self) -> None: ...

    def slewCCW(self) -> None: ...

    def abortSlew(self) -> None: ...


@runtime_checkable
class FocuserDriver(FrameworkDriver, Protocol):
    def move(self, position: int) -> None: ...

    def halt(self) -> None: ...


@runtime_checkable
class FilterDriver(FrameworkDriver, Protocol):
    def sendFilterNumber(self, filterNumber: int) -> None: ...


@runtime_checkable
class CoverDriver(FrameworkDriver, Protocol):
    def openCover(self) -> None: ...

    def closeCover(self) -> None: ...

    def haltCover(self) -> None: ...


@runtime_checkable
class LightPanelDriver(FrameworkDriver, Protocol):
    def lightOn(self) -> None: ...

    def lightOff(self) -> None: ...

    def lightIntensity(self, value: int) -> None: ...


@runtime_checkable
class PowerSwitchDriver(FrameworkDriver, Protocol):
    def togglePowerPort(self, port: str) -> None: ...

    def togglePortUSB(self, port: str) -> None: ...

    def toggleHubUSB(self) -> None: ...

    def sendDew(self, port: str, value: float) -> None: ...

    def sendAdjustableOutput(self, value: float) -> None: ...

    def reboot(self) -> None: ...


@runtime_checkable
class PlateSolveDriver(HasDriverConfig, Protocol):
    returnCodes: ClassVar[dict[int, str]]

    def solve(self, imagePath: Path, updateHeader: bool) -> dict[str, Any]: ...

    def checkAvailabilityProgram(self, appPath: str) -> bool: ...

    def checkAvailabilityIndex(self, indexPath: str) -> bool: ...
